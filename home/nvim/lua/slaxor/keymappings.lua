vim.keymap.set('n', '<C-=>', function()
  local word = vim.fn.expand '<cword>'
  local rval = ''
  if word == 'true' then
  	rval = 'm`ciwfalse<Esc>``'
  elseif word == 'false' then
  	rval = 'm`ciwtrue<Esc>``'
  elseif word == 'True' then
  	rval = 'm`ciwFalse<Esc>``'
  elseif word == 'False' then
  	rval = 'm`ciwTrue<Esc>``'
  end
  return rval
end, { expr = true, desc = 'Toggle boolean' })
